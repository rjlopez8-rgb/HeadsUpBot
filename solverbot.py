"""
solverbot.py - plays the CFR+ blueprint (solver/cfr.py) with an exploit layer.

Per decision:
  1. Find the betting-tree node from the actions so far (exact: the tree was
     generated by the official engine, so every real sequence is in it).
  2. Bucket our hand: equity vs a random hand, same estimator and sample
     count as in training, then the same equal-mass thresholds.
  3. Read the blueprint's mixed strategy for (node, bucket) and sample it.
  4. Exploit layer (only when the evidence is strong):
       * opponent folds to nearly every bet (e.g. a bot whose time bank ran
         out plays check/fold) -> raise at every chance
       * opponent folds a lot -> turn some blueprint checks into bluffs
       * opponent rarely folds -> drop the blueprint's weak-hand bluffs
       * opponent is hyper-aggressive -> call down lighter
  5. Anything unexpected -> fall back to hero.py (never crash).
"""

from __future__ import annotations

import os
import time
from dataclasses import dataclass

import numpy as np

import pokerlib as pl
from game import Action, Street
from hero import Hero, Params

F, C, RH, RP = Action.FOLD, Action.CHECK_CALL, Action.RAISE_HALF, Action.RAISE_POT
AGGR = (RH, RP)
K_SAMPLES = (128, 128, 128, 160)          # must match solver/dataset.py
_HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_STRATEGY = os.path.join(_HERE, "data", "strategy.npz")


class Blueprint:
    def __init__(self, path: str = DEFAULT_STRATEGY):
        z = np.load(path, allow_pickle=False)
        self.K = int(z["K"])
        self.thr = z["thr"]
        self.strategy = z["strategy"]
        self.players = z["players"]
        self.index = {k: j for j, k in enumerate(z["keys"].tolist())}

    def node(self, history) -> int:
        return self.index.get(repr(tuple(int(a.action) for a in history)), -1)

    def bucket(self, street: int, e: float) -> int:
        return int(np.searchsorted(self.thr[street], e, side="right"))


# ---------------------------------------------------------------- time guard
# The judge allows 8 s of thinking per 1000-hand half and 1 s per request.
# We aim for TIME_TARGET (a quarter of the bank) and degrade in steps if the
# machine is slow: fewer Monte Carlo samples -> slightly noisier buckets, but
# never an empty time bank. Typical use on a normal core is ~1.3 s per half.
TIME_TARGET = 2.0
HARD_CAP = 5.0          # past this, use the bare minimum of samples


def samples_for(base: int, used: float, hand_index: int) -> int:
    pace = TIME_TARGET * (hand_index + 1) / 1000.0
    if used > HARD_CAP:
        return 16
    if used > 1.5 * pace:
        return 32
    if used > pace:
        return max(48, base // 2)
    return base


_CACHE: dict = {}


def load_blueprint(path: str = DEFAULT_STRATEGY) -> Blueprint:
    if path not in _CACHE:
        _CACHE[path] = Blueprint(path)
    return _CACHE[path]


@dataclass
class XParams:
    exploit_window: int = 16
    exploit_folds: int = 14
    bluff_more: float = 0.6       # extra bluff prob per unit of fold rate above fold_hi
    fold_hi: float = 0.55
    fold_lo: float = 0.25         # below this, drop weak-hand bluffs
    weak_frac: float = 0.4        # "weak" = bucket below this fraction of K
    aggr_hi: float = 0.55         # opponent raise rate considered hyper-aggressive
    call_light: float = 0.6       # chance to overrule a fold vs hyper-aggression if equity >= odds
    min_obs: int = 40             # opponent actions needed before adapting
    seed: int = 7


class SolverBot:
    def __init__(self, path: str = DEFAULT_STRATEGY, xp: XParams | None = None, exploit: bool = True):
        self.bp = load_blueprint(path)
        self.xp = xp or XParams()
        self.exploit = exploit
        self.fallback = Hero(Params())

    def new_half(self, config, m):
        m.clear()
        self.fallback.new_half(config, m)        # hero's tracking state lives in the same dict
        m["xrng"] = np.random.default_rng(self.xp.seed)
        m["sb_t"] = 0.0
        m["fallbacks"] = 0

    def on_hand_end(self, result, m):
        self.fallback.on_hand_end(result, m)

    def choose_action(self, obs, m):
        t0 = time.perf_counter()
        try:
            a = self._decide(obs, m)
            if a not in obs.legal_actions:
                raise ValueError("illegal")
        except Exception:  # noqa: BLE001
            m["fallbacks"] = m.get("fallbacks", 0) + 1
            try:
                a = self.fallback._decide(obs, m)
            except Exception:  # noqa: BLE001
                a = C
            if a not in obs.legal_actions:
                a = C
        m["sb_t"] = m.get("sb_t", 0.0) + time.perf_counter() - t0
        if a in AGGR:
            m["we_bet_last"] = True
        return a

    def _decide(self, obs, m):
        self.fallback._track(obs, m)               # opponent stats (shared with hero)
        rng = m["xrng"]
        legal = obs.legal_actions
        can_raise = RH in legal or RP in legal
        xp = self.xp

        if self.exploit and can_raise and self.fallback._exploit_mode(m):
            return RH if RH in legal else RP

        j = self.bp.node(obs.action_history)
        if j < 0:
            raise KeyError("node not in tree")
        me = 0 if obs.is_button else 1
        if int(self.bp.players[j]) != me:
            raise ValueError("player mismatch")
        st = int(obs.street)
        n = samples_for(K_SAMPLES[st], m.get("sb_t", 0.0), obs.hand_index)
        e = pl.equity(obs.hole_cards, obs.board, n, rng)
        b = self.bp.bucket(st, e)
        probs = self.bp.strategy[j, b].astype(np.float64).copy()
        mask = np.zeros(4)
        for a in legal:
            mask[int(a)] = 1.0
        probs *= mask
        if probs.sum() <= 0:
            probs = mask
        probs /= probs.sum()
        a = Action(int(rng.choice(4, p=probs)))

        if not self.exploit:
            return a
        nact = m["opp_acts"][0] + m["opp_acts"][1]
        if nact < xp.min_obs:
            return a
        fold_rate = self.fallback._fold_rate(m)
        g = 0 if obs.street == Street.PREFLOP else 1
        aggr = self.fallback._aggr_rate(m, g)
        weak = b < xp.weak_frac * self.bp.K
        if a == C and obs.to_call == 0 and can_raise and fold_rate > xp.fold_hi:
            if rng.random() < xp.bluff_more * (fold_rate - xp.fold_hi):
                return RH if RH in legal else RP
        if a in AGGR and weak and fold_rate < xp.fold_lo:
            return C
        if a == F and aggr > xp.aggr_hi and obs.to_call > 0:
            odds = obs.to_call / (obs.pot + obs.to_call)
            if e >= odds and rng.random() < xp.call_light:
                return C
        return a
