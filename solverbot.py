"""
solverbot.py - plays the CFR+ blueprint (solver/cfr.py) with an exploit layer.

Per decision:
  1. Find the betting-tree node from the actions so far (exact: the tree was
     generated by the official engine, so every real sequence is in it).
  2. Bucket our hand: equity vs a random hand, same estimator and sample
     count as in training, then the same equal-mass thresholds.
  3. Read the blueprint's mixed strategy for (node, bucket) and sample it.
  4. Exploit layer (only when the evidence is strong):
       * opponent folds to nearly every bet (e.g. a bot whose time bank ran
         out plays check/fold) -> raise at every chance
       * opponent folds a lot -> turn some blueprint checks into bluffs
       * opponent rarely folds -> drop the blueprint's weak-hand bluffs
       * opponent is hyper-aggressive -> call down lighter
  5. Anything unexpected -> fall back to hero.py (never crash).
"""

from __future__ import annotations

import os
import time
from dataclasses import dataclass

import numpy as np

import pokerlib as pl
from game import Action, Street
from solver.features import batch_ehs2
from hero import Hero, Params

F, C, RH, RP = Action.FOLD, Action.CHECK_CALL, Action.RAISE_HALF, Action.RAISE_POT
AGGR = (RH, RP)
K_SAMPLES = (128, 128, 128, 160)          # must match solver/dataset.py
H2_RUNOUTS, H2_OPPS = 16, 16                # must match solver/features.py
_HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_STRATEGY = os.path.join(_HERE, "data", "strategy.npz")


class Blueprint:
    def __init__(self, path: str = DEFAULT_STRATEGY):
        z = np.load(path, allow_pickle=False)
        self.K = int(z["K"])
        self.thr = z["thr"]
        self.strategy = z["strategy"]
        self.players = z["players"]
        self.index = {k: j for j, k in enumerate(z["keys"].tolist())}
        self.feature = str(z["feature"]) if "feature" in z.files else "hs"
        # a blueprint may ship its own preflop table (the one it was trained with):
        # <strategy>.preflop.npy next to the strategy file; else the global table
        pf = path.replace(".npz", ".preflop.npy")
        self.preflop = np.load(pf) if os.path.exists(pf) else None

    def preflop_eq(self, hole) -> float:
        if self.preflop is not None:
            return float(self.preflop[pl.colex(np.asarray(hole))])
        return float(pl.preflop_eq(np.asarray(hole)))

    def node(self, history) -> int:
        return self.index.get(repr(tuple(int(a.action) for a in history)), -1)

    def bucket(self, street: int, e: float) -> int:
        return int(np.searchsorted(self.thr[street], e, side="right"))


# ---------------------------------------------------------------- time guard
# The judge allows 8 s of thinking per 1000-hand half and 1 s per request.
# We aim for TIME_TARGET (a quarter of the bank) and degrade in steps if the
# machine is slow: fewer Monte Carlo samples -> slightly noisier buckets, but
# never an empty time bank. Typical use on a normal core is ~1.3 s per half.
TIME_TARGET = float(os.environ.get("SOLVERBOT_TIME_TARGET", "2.5"))
HARD_CAP = max(5.0, TIME_TARGET * 2.5)   # past this, use the bare minimum of samples


def budget_fraction(used: float, hand_index: int) -> float:
    """Share of the full sample count we can afford right now (1, .5, .25, .1)."""
    pace = TIME_TARGET * (hand_index + 1) / 1000.0
    if used > HARD_CAP:
        return 0.1
    if used > 1.5 * pace:
        return 0.25
    if used > pace:
        return 0.5
    return 1.0


def samples_for(base: int, used: float, hand_index: int) -> int:
    return max(16, int(base * budget_fraction(used, hand_index)))


OVERHEAD_PER_CALL = 0.0004   # judge also charges HTTP/JSON handling we can't time


def charged_estimate(m) -> float:
    """Our thinking time plus an estimate of the per-request overhead the
    judge charges (it times the whole request, minus a 1 ms grace)."""
    return m.get("sb_t", 0.0) + OVERHEAD_PER_CALL * m.get("calls", 0)


_CACHE: dict = {}


def load_blueprint(path: str = DEFAULT_STRATEGY) -> Blueprint:
    if path not in _CACHE:
        _CACHE[path] = Blueprint(path)
    return _CACHE[path]


@dataclass
class XParams:
    exploit_window: int = 16
    exploit_folds: int = 14
    bluff_more: float = 0.6       # extra bluff prob per unit of fold rate above fold_hi
    fold_hi: float = 0.55
    fold_lo: float = 0.25         # below this, drop weak-hand bluffs
    weak_frac: float = 0.4        # "weak" = bucket below this fraction of K
    aggr_hi: float = 0.55         # opponent raise rate considered hyper-aggressive
    call_light: float = 0.6       # chance to overrule a fold vs hyper-aggression if equity >= odds
    min_obs: int = 40             # opponent actions needed before adapting
    seed: int = 7


class SolverBot:
    def __init__(self, path: str = DEFAULT_STRATEGY, xp: XParams | None = None, exploit: bool = True,
                 fold_exploit: bool = True, precision: float | None = None):
        self.bp = load_blueprint(path)
        # multiplier on all Monte Carlo sample counts (1 = training estimator)
        self.precision = precision if precision is not None else float(os.environ.get("SOLVERBOT_PRECISION", "4"))
        self.xp = xp or XParams()
        self.exploit = exploit              # blueprint tweaks vs extreme opponents
        self.fold_exploit = fold_exploit    # raise everything vs check/fold bots
        self.fallback = Hero(Params())

    def new_half(self, config, m):
        m.clear()
        self.fallback.new_half(config, m)        # hero's tracking state lives in the same dict
        m["xrng"] = np.random.default_rng(self.xp.seed)
        m["sb_t"] = 0.0
        m["fallbacks"] = 0

    def on_hand_end(self, result, m):
        self.fallback.on_hand_end(result, m)

    def choose_action(self, obs, m):
        t0 = time.perf_counter()
        try:
            a = self._decide(obs, m)
            if a not in obs.legal_actions:
                raise ValueError("illegal")
        except Exception:  # noqa: BLE001
            m["fallbacks"] = m.get("fallbacks", 0) + 1
            try:
                a = self.fallback._decide(obs, m)
            except Exception:  # noqa: BLE001
                a = C
            if a not in obs.legal_actions:
                a = C
        m["sb_t"] = m.get("sb_t", 0.0) + time.perf_counter() - t0
        m["calls"] = m.get("calls", 0) + 1
        if a in AGGR:
            m["we_bet_last"] = True
        return a

    def _blueprint(self, obs, m):
        """The blueprint's sampled action plus our equity and bucket."""
        rng = m["xrng"]
        j = self.bp.node(obs.action_history)
        if j < 0:
            raise KeyError("node not in tree")
        me = 0 if obs.is_button else 1
        if int(self.bp.players[j]) != me:
            raise ValueError("player mismatch")
        st = int(obs.street)
        f = budget_fraction(charged_estimate(m), obs.hand_index) * self.precision
        n = max(16, int(K_SAMPLES[st] * f))
        if self.bp.feature == "h2" and st in (1, 2):
            # one E[HS^2] pass gives both E[HS] (for overrides) and the bucket feature
            side = max(8, int(round(16 * f ** 0.5)))
            h = np.asarray(obs.hole_cards, dtype=np.int64)[None, :]
            board = np.zeros((1, 5), dtype=np.int64)
            board[0, :len(obs.board)] = obs.board
            ehs, ehs2 = batch_ehs2(h, board, len(obs.board), rng, side, side)
            e, feat = float(ehs[0]), float(ehs2[0])
        elif st == 0:
            e = self.bp.preflop_eq(obs.hole_cards)
            feat = e
        else:
            e = pl.equity(obs.hole_cards, obs.board, n, rng)
            feat = self.feature(st, e, obs, m, n)
        b = self.bp.bucket(st, feat)
        probs = self.bp.strategy[j, b].astype(np.float64).copy()
        mask = np.zeros(4)
        for a in obs.legal_actions:
            mask[int(a)] = 1.0
        probs *= mask
        if probs.sum() <= 0:
            probs = mask
        probs /= probs.sum()
        return Action(int(rng.choice(4, p=probs))), e, b

    def feature(self, st, e, obs, m, n):
        """Bucketing feature, matching how the blueprint was trained:
        "hs": equity vs a random hand (E[HS]); "h2": E[HS^2] on flop/turn,
        HS^2 on the river, table equity preflop."""
        if self.bp.feature != "h2" or st == 0:
            return e
        if st == 3:
            return e * e
        R = H2_RUNOUTS if n >= 96 else 8
        h = np.asarray(obs.hole_cards, dtype=np.int64)[None, :]
        board = np.zeros((1, 5), dtype=np.int64)
        board[0, :len(obs.board)] = obs.board
        return float(batch_ehs2(h, board, len(obs.board), m["xrng"], R, H2_OPPS)[1][0])

    def _decide(self, obs, m):
        self.fallback._track(obs, m)               # opponent stats (shared with hero)
        rng = m["xrng"]
        legal = obs.legal_actions
        can_raise = RH in legal or RP in legal
        xp = self.xp

        if (self.exploit or self.fold_exploit) and can_raise and self.fallback._exploit_mode(m):
            return RH if RH in legal else RP

        a, e, b = self._blueprint(obs, m)

        if not self.exploit:
            return a
        nact = m["opp_acts"][0] + m["opp_acts"][1]
        if nact < xp.min_obs:
            return a
        fold_rate = self.fallback._fold_rate(m)
        g = 0 if obs.street == Street.PREFLOP else 1
        aggr = self.fallback._aggr_rate(m, g)
        weak = b < xp.weak_frac * self.bp.K
        if a == C and obs.to_call == 0 and can_raise and fold_rate > xp.fold_hi:
            if rng.random() < xp.bluff_more * (fold_rate - xp.fold_hi):
                return RH if RH in legal else RP
        if a in AGGR and weak and fold_rate < xp.fold_lo:
            return C
        if a == F and aggr > xp.aggr_hi and obs.to_call > 0:
            odds = obs.to_call / (obs.pot + obs.to_call)
            if e >= odds and rng.random() < xp.call_light:
                return C
        return a


# ------------------------------------------------------------------ hybrid
# Opponent "fingerprint" of the blueprint itself (measured in self-play):
# preflop raise rate, postflop raise rate, how often it folds to our bets.
EQ_PROFILE = (0.47, 0.39, 0.41)


@dataclass
class HParams:
    decide_at: int = 100          # hands of blueprint play before the first decision
    recheck_every: int = 150
    d_hi: float = 0.13            # deviation above this -> exploit (hero mode)
    d_lo: float = 0.08            # deviation below this -> back to blueprint
    w_pre: float = 1.0
    w_post: float = 1.0
    w_fold: float = 1.0


class Hybrid(SolverBot):
    """Blueprint by default; hero-style exploitation once the opponent's
    statistics are clearly far from equilibrium play."""

    def __init__(self, path: str = DEFAULT_STRATEGY, hp: HParams | None = None,
                 hero_params: Params | None = None, exploit: bool = False, **kw):
        # balanced mode = pure blueprint (+ the check/fold-bot exploit only)
        super().__init__(path, exploit=exploit, **kw)
        self.hp = hp or HParams()
        if hero_params is not None:
            self.fallback = Hero(hero_params)

    def new_half(self, config, m):
        super().new_half(config, m)
        m["mode"] = "bp"
        m["next_check"] = self.hp.decide_at
        m["mode_log"] = []

    def deviation(self, m) -> float:
        hp = self.hp
        pre = m["opp_aggr"][0] / max(1, m["opp_acts"][0])
        post = m["opp_aggr"][1] / max(1, m["opp_acts"][1])
        log = m["bet_log"]
        fold = sum(log) / max(1, len(log))
        e = EQ_PROFILE
        return (hp.w_pre * abs(pre - e[0]) + hp.w_post * abs(post - e[1]) + hp.w_fold * abs(fold - e[2])) / \
            (hp.w_pre + hp.w_post + hp.w_fold)

    def _decide(self, obs, m):
        if obs.hand_index >= m["next_check"] and m["cur_hand"] != obs.hand_index:
            d = self.deviation(m)
            if m["mode"] == "bp" and d > self.hp.d_hi:
                m["mode"] = "hero"
            elif m["mode"] == "hero" and d < self.hp.d_lo:
                m["mode"] = "bp"
            m["mode_log"].append((obs.hand_index, round(d, 3), m["mode"]))
            m["next_check"] = obs.hand_index + self.hp.recheck_every
        if m["mode"] == "hero":
            return self.fallback._decide(obs, m)       # tracks stats itself
        return super()._decide(obs, m)


# ---------------------------------------------------------- hybrid, overrides
@dataclass
class OParams:
    margin: float = 0.0246        # R1: fold if range equity < odds + margin (tuned)
    range_k: float = 1.6          # opponent range = top (aggr_rate * range_k) of hands
    range_min: float = 0.12
    tight_ratio: float = 0.75     # R1 active if opp aggression < tight_ratio * equilibrium
    fold_gap: float = 0.10        # R2/R3 active if fold rate is this far from equilibrium
    weak_frac: float = 0.45       # bluff = blueprint raise from a bucket below this share of K
    value_eq: float = 0.6017      # R2: bet for value vs callers from this equity (tuned)
    bluff_scale: float = 1.2      # R3: extra bluff prob per unit of excess fold rate
    loose_ratio: float = 1.35     # R4 active if opp aggression > loose_ratio * equilibrium
    r1: bool = True               # fold more vs honest/tight aggressors
    r2: bool = True               # no bluffs + thin value vs calling stations
    r3: bool = True               # bluff over-folders
    r4: bool = False              # call down maniacs: OFF - red team showed aggressive bots exploit it
    # showdown evidence: share of the opponent's revealed bets/raises made with weak hands
    sd_use: bool = True
    sd_min: int = 12              # revealed aggressive actions needed before trusting the bluff rate
    sd_weak_eq: float = 0.40      # an aggressive action with hand equity below this = a bluff
    sd_eq_rate: float = 0.17      # the blueprint's own bluff rate measured the same way (0.15-0.19)
    sd_gap: float = 0.08          # how far from sd_eq_rate before acting on it
    sd_call_margin: float = 0.02  # R5: vs over-bluffers, call if equity >= odds - this
    sd_window: int = 40           # only the most recent revealed actions count (vs style switchers)
    sd_switch: bool = False       # over-bluffing alone switches the exploit layer on (tested: neutral, so off)


class HybridX(Hybrid):
    """Blueprint always; in exploit mode, override specific blueprint actions
    where the opponent's statistics reveal a leak (never abandons the
    blueprint wholesale, so it keeps its edge vs strong heuristic bots)."""

    def __init__(self, path: str = DEFAULT_STRATEGY, op: OParams | None = None, **kw):
        super().__init__(path, **kw)
        self.op = op or OParams()

    def new_half(self, config, m):
        super().new_half(config, m)
        m["sd_aggr"] = 0           # opponent bets/raises revealed at showdown
        m["sd_weak"] = 0           # ... of which made with a weak hand
        m["hist_hand"] = -1
        m["hist"] = ()

    def choose_action(self, obs, m):
        m["hist_hand"] = obs.hand_index
        m["hist"] = obs.action_history
        return super().choose_action(obs, m)

    def on_hand_end(self, result, m):
        super().on_hand_end(result, m)
        try:
            self._learn_showdown(result, m)
        except Exception:  # noqa: BLE001 - learning must never break play
            pass

    def _learn_showdown(self, result, m):
        if not self.op.sd_use or not result.went_to_showdown or result.opp_hole is None:
            return
        if m.get("hist_hand") != result.hand_index:
            return
        streets = sorted({int(a.street) for a in m["hist"] if not a.is_me and a.action in AGGR})
        if not streets:
            return
        rng = m["xrng"]
        board = list(result.board)
        for st in streets:
            if st == 0:
                eq = self.bp.preflop_eq(result.opp_hole)
            else:
                eq = pl.equity(result.opp_hole, board[:(3, 4, 5)[st - 1]], 96, rng)
            m["sd_aggr"] += 1
            weak = eq < self.op.sd_weak_eq
            if weak:
                m["sd_weak"] += 1
            log = m.setdefault("sd_log", [])
            log.append(1 if weak else 0)
            if len(log) > self.op.sd_window:
                del log[0]

    def bluff_rate(self, m):
        """Opponent's observed bluff rate, or None until there is enough evidence."""
        log = m.get("sd_log", [])
        if len(log) < self.op.sd_min:
            return None
        return (sum(log) + self.op.sd_eq_rate * 4) / (len(log) + 4)

    def _decide(self, obs, m):
        if obs.hand_index >= m["next_check"] and m["cur_hand"] != obs.hand_index:
            d = self.deviation(m)
            # proven over-bluffing switches the exploit layer on even when the raw
            # frequencies look balanced (a smart adaptive bluffer would look balanced)
            br = self.bluff_rate(m)
            bluffy = (self.op.sd_switch and br is not None
                      and br > self.op.sd_eq_rate + self.op.sd_gap)
            if m["mode"] == "bp" and (d > self.hp.d_hi or bluffy):
                m["mode"] = "x"
            elif m["mode"] == "x" and d < self.hp.d_lo and not bluffy:
                m["mode"] = "bp"
            m["mode_log"].append((obs.hand_index, round(d, 3), m["mode"]))
            m["next_check"] = obs.hand_index + self.hp.recheck_every
        self.fallback._track(obs, m)
        legal = obs.legal_actions
        can_raise = RH in legal or RP in legal
        if can_raise and self.fallback._exploit_mode(m):
            return RH if RH in legal else RP
        a, e, b = self._blueprint(obs, m)
        if m["mode"] != "x":
            return a
        return self._override(obs, m, a, e, b)

    def _override(self, obs, m, a, e, b):
        op, rng = self.op, m["xrng"]
        legal = obs.legal_actions
        can_raise = RH in legal or RP in legal
        g = 0 if obs.street == Street.PREFLOP else 1
        aggr = self.fallback._aggr_rate(m, g)
        a_eq = EQ_PROFILE[g]
        fold_rate = self.fallback._fold_rate(m)
        f_eq = EQ_PROFILE[2]
        facing = obs.to_call > 0
        opp_raised = any(x.street == obs.street and not x.is_me and x.action in AGGR
                         for x in obs.action_history)
        weak = b < op.weak_frac * self.bp.K
        br = self.bluff_rate(m)
        over_bluffer = br is not None and br > op.sd_eq_rate + op.sd_gap
        never_bluffs = br is not None and br < op.sd_eq_rate - op.sd_gap
        if facing and opp_raised:
            odds = obs.to_call / (obs.pot + obs.to_call)
            if over_bluffer and a == F and e >= odds - op.sd_call_margin:
                return C                                   # R5: call down proven over-bluffers
            tight = aggr < op.tight_ratio * a_eq or never_bluffs
            if op.r1 and tight and not over_bluffer and a != F:
                # R1: honest/tight aggressor - check our equity vs its real range
                keep = min(1.0, max(op.range_min, aggr * op.range_k))
                er = pl.equity(obs.hole_cards, obs.board, 160, rng, keep)
                if er < odds + op.margin and F in legal:
                    return F
                if a in AGGR and er < 0.5:
                    return C
            if op.r4 and aggr > op.loose_ratio * a_eq and a == F and e >= odds:
                return C                                   # R4: call down a maniac
        if op.r2 and a in AGGR and weak and fold_rate < f_eq - op.fold_gap:
            return C                                       # R2: no bluffs vs callers
        if (op.r2 and a == C and not facing and can_raise and fold_rate < f_eq - op.fold_gap
                and e >= op.value_eq):
            return RH if RH in legal else RP               # R2: thin value vs callers
        if (op.r3 and a == C and not facing and can_raise and fold_rate > f_eq + op.fold_gap
                and rng.random() < op.bluff_scale * (fold_rate - f_eq - op.fold_gap)):
            return RH if RH in legal else RP               # R3: bluff over-folders
        return a
